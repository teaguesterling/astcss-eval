#!/usr/bin/env bash
# refresh-duckdb-extensions.sh — regenerate collections/duckdb-extensions.txt.
#
# The list = curated core extensions + curated third-party community
# extensions + every community extension YOU maintain. The last set is
# auto-discovered by installing the `yaml` extension and querying the
# community-extensions repo's description.yml maintainer fields — so newly
# published extensions get picked up without hand-editing.
#
# Run from a host that has the community-extensions repo cloned (e.g. snape):
#   ./refresh-duckdb-extensions.sh
#
# Overrides via env: COMMUNITY_EXT_REPO, DUCKDB, DUCKDB_MAINTAINER.

set -euo pipefail

DIR="$(cd "$(dirname "$0")" && pwd)"
CE="${COMMUNITY_EXT_REPO:-$HOME/Projects/duckdb-community-extensions}"
DUCKDB="${DUCKDB:-$(command -v duckdb || echo "$HOME/.bin/duckdb")}"
MAINTAINER="${DUCKDB_MAINTAINER:-teaguesterling}"
OUT="$DIR/collections/duckdb-extensions.txt"

[ -x "$DUCKDB" ] || { echo "duckdb not found ($DUCKDB)"; exit 1; }
[ -d "$CE/extensions" ] || { echo "community-extensions repo not at $CE"; exit 1; }

# Curated (edit these by hand as needed):
CORE="aws core_functions ducklake encodings excel fts httpfs icu motherduck postgres_scanner spatial sqlite_scanner vortex vss"
THIRD_PARTY_COMMUNITY="duckhts"   # community exts you use but don't maintain

# Auto-discover the community extensions you maintain.
sql="$(mktemp)"
cat > "$sql" <<SQL
INSTALL yaml FROM community; LOAD yaml;
SELECT extension.name
FROM read_yaml('$CE/extensions/*/description.yml')
WHERE list_contains(extension.maintainers, '$MAINTAINER')
ORDER BY 1;
SQL
mine="$("$DUCKDB" -noheader -list -c ".read $sql")"
rm -f "$sql"

{
  echo "# name <space> source   (core => INSTALL name;  community => INSTALL name FROM community)"
  echo "# Generated by refresh-duckdb-extensions.sh. Edit CORE/THIRD_PARTY_COMMUNITY"
  echo "# in that script; the maintained set is auto-discovered via the yaml extension."
  for e in $CORE; do echo "$e core"; done
  printf '%s\n' $THIRD_PARTY_COMMUNITY $mine | sort -u | sed 's/$/ community/'
} > "$OUT"

echo "wrote $OUT ($(grep -vcE '^\s*#' "$OUT") extensions; $(echo "$mine" | grep -c .) maintained)"
